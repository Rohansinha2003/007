"""Render a Resume as ATS-safe DOCX and PDF (one column, no tables, images, text boxes or headers/footers),
plus evidence.md for your own review.

Each bullet in the DOCX carries its evidence ids as a hidden run ("[evidence: E12 E40]"). Word does not
show or print hidden text; turn on "Hidden text" in Word to see it. The PDF has no ids.
"""
from __future__ import annotations

from pathlib import Path

from .generate import Resume

ASCII = {"‘": "'", "’": "'", "“": '"', "”": '"', "–": "-", "—": "-", "•": "-",
         "…": "...", " ": " ", "→": "->", " ": " "}


def _contact(h: dict) -> str:
    return " | ".join(x for x in [h.get("email"), h.get("phone"), h.get("location"), *h.get("links", [])] if x)


def _skill_lines(r: Resume) -> list[tuple[str, str]]:
    langs = [s.name for s in r.skills if s.kind == "language"]
    other = [s.name for s in r.skills if s.kind != "language"]
    return [(label, ", ".join(names)) for label, names in (("Languages", langs), ("Technologies", other)) if names]


def _project_line(p) -> str:
    parts = [p.name]
    if p.stack:
        parts.append(", ".join(p.stack))
    link = p.deployed_url or p.url
    if link:
        parts.append(link)
    if p.dates:
        parts.append(p.dates)
    return " | ".join(parts)


def ids_label(ids: list[int]) -> str:
    return "[evidence: " + " ".join(f"E{i}" for i in ids) + "]"


# ---------- DOCX ----------

def to_docx(r: Resume, path: str | Path, hidden_ids: bool = True) -> Path:
    from docx import Document
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.shared import Inches, Pt

    doc = Document()
    for s in doc.sections:
        s.top_margin = s.bottom_margin = Inches(0.6)
        s.left_margin = s.right_margin = Inches(0.7)
    normal = doc.styles["Normal"]
    normal.font.name = "Calibri"
    normal.font.size = Pt(10.5)
    normal.paragraph_format.space_after = Pt(2)

    def para(text="", bold=False, size=None, align=None, space_before=0):
        p = doc.add_paragraph()
        if text:
            run = p.add_run(text)
            run.bold = bold
            if size:
                run.font.size = Pt(size)
        if align:
            p.alignment = align
        p.paragraph_format.space_before = Pt(space_before)
        return p

    def hidden(p, ids):
        if hidden_ids and ids:
            run = p.add_run(" " + ids_label(ids))
            run.font.hidden = True

    para(r.header["name"], bold=True, size=16, align=WD_ALIGN_PARAGRAPH.CENTER)
    if _contact(r.header):
        para(_contact(r.header), align=WD_ALIGN_PARAGRAPH.CENTER)
    if r.skills:
        para("SKILLS", bold=True, size=11.5, space_before=8)
        by_name = {s.name: s for s in r.skills}
        for label, names in _skill_lines(r):
            p = para()
            p.add_run(f"{label}: ").bold = True
            p.add_run(names)
            hidden(p, sorted({i for n in names.split(", ") for i in by_name[n].evidence_ids[:3]}))
    para("PROJECTS", bold=True, size=11.5, space_before=8)
    for proj in r.projects:
        p = para(space_before=4)
        p.add_run(proj.name).bold = True
        rest = _project_line(proj)[len(proj.name):]
        if rest:
            p.add_run(rest)
        hidden(p, proj.stack_evidence)
        for b in proj.kept:
            bp = doc.add_paragraph(style="List Bullet")
            bp.add_run(b.text)
            hidden(bp, b.evidence_ids)
    doc.core_properties.title = f"Resume - {r.header['name']}"
    doc.core_properties.comments = "Generated by resumeforge; bullet evidence ids are hidden text."
    path = Path(path)
    doc.save(path)
    return path


# ---------- PDF ----------

def _latin(text: str) -> str:
    for a, b in ASCII.items():
        text = text.replace(a, b)
    return text.encode("latin-1", "replace").decode("latin-1")


def to_pdf(r: Resume, path: str | Path, compress: bool = True) -> Path:
    from fpdf import FPDF

    pdf = FPDF(format="Letter", unit="pt")
    pdf.set_compression(compress)
    pdf.set_margins(50, 43, 50)
    pdf.set_auto_page_break(True, 43)
    pdf.add_page()
    pdf.set_title(_latin(f"Resume - {r.header['name']}"))
    w = pdf.w - pdf.l_margin - pdf.r_margin

    def text(t, size=10.5, style="", align="L", h=None, indent=0):
        pdf.set_font("Helvetica", style, size)
        pdf.set_x(pdf.l_margin + indent)
        pdf.multi_cell(w - indent, h or size * 1.3, _latin(t), align=align, new_x="LMARGIN", new_y="NEXT")

    def heading(t):
        pdf.ln(6)
        text(t, 11.5, "B")
        y = pdf.get_y()
        pdf.line(pdf.l_margin, y, pdf.l_margin + w, y)
        pdf.ln(3)

    text(r.header["name"], 16, "B", "C", 20)
    if _contact(r.header):
        text(_contact(r.header), align="C")
    if r.skills:
        heading("SKILLS")
        for label, names in _skill_lines(r):
            text(f"{label}: {names}")
    heading("PROJECTS")
    for proj in r.projects:
        pdf.ln(3)
        text(_project_line(proj), style="B")
        for b in proj.kept:
            pdf.set_font("Helvetica", "", 10.5)
            pdf.set_x(pdf.l_margin + 8)
            pdf.cell(10, 13.65, "-")
            pdf.multi_cell(w - 18, 13.65, _latin(b.text), align="L", new_x="LMARGIN", new_y="NEXT")
    path = Path(path)
    pdf.output(str(path))
    return path


# ---------- evidence.md ----------

def _link(row) -> str:
    u = row["url_or_path"]
    return f"[{u}]({u})" if u.startswith("http") else f"`{u}`"


def to_evidence_md(r: Resume, conn, path: str | Path) -> Path:
    ids = sorted({i for p in r.projects for b in p.bullets for i in b.evidence_ids}
                 | {i for p in r.projects for i in p.stack_evidence} | {i for s in r.skills for i in s.evidence_ids})
    rows = {}
    if ids:
        q = f"SELECT id, kind, source, url_or_path, created_at, snippet FROM evidence WHERE id IN ({','.join('?' * len(ids))})"
        rows = {row["id"]: row for row in conn.execute(q, ids)}

    def cite(i):
        row = rows.get(i)
        if row is None:
            return f"  - E{i}: missing"
        snippet = " ".join(row["snippet"].split())
        snippet = snippet[:160] + ("..." if len(snippet) > 160 else "")
        return f"  - E{i} · {row['kind']} · {(row['created_at'] or '')[:10]} · {_link(row)}\n    > {snippet}"

    m = r.meta
    out = [f"# Evidence for {r.header['name']}'s resume", "",
           f"Generated {m['generated_at']} for: **{r.jd_title or 'job description'}**  ",
           f"Bullet writer: {m['writer']}. Claim check: {', '.join(m['checkers']) or 'none'}. "
           f"JD skills read by: {m['jd_extractor']}. Evaluator role: {m.get('evaluated_role') or 'none'}.", ""]
    have = [s["skill"] for s in r.jd_skills if s["have"]]
    lack = [f"{s['skill']} ({s['requirement']})" for s in r.jd_skills if not s["have"]]
    out += ["## Fit with the job description", "",
            f"- Asked for and backed by evidence: {', '.join(have) or 'none'}",
            f"- Asked for, no evidence, so not claimed: {', '.join(lack) or 'none'}", ""]
    out += ["## Projects", ""]
    for p in r.projects:
        out += [f"### {p.name}", "",
                f"Evaluator: {p.decision} (score {p.score:.2f}). JD fit {p.fit:.2f}"
                + (f" via {', '.join(p.jd_matches)}" if p.jd_matches else "") + f". Writer: {p.writer or m['writer']}.", "",
                f"Project line: {_project_line(p)}"]
        out += [cite(i) for i in p.stack_evidence]
        out.append("")
        for n, b in enumerate(p.kept, 1):
            mark = "" if b.status == "verified" else " **[FLAGGED]**"
            out += [f"{n}. {b.text}{mark}", f"   - check ({b.checker or 'none'}): {b.reason or '-'}"]
            out += ["  " + c for c in (cite(i) for i in b.evidence_ids)]
            out.append("")
    out += ["## Skills", ""]
    for s in r.skills:
        out.append(f"- **{s.name}** ({s.kind}, evaluator {s.decision}{', in JD' if s.in_jd else ''})")
        out += ["  " + cite(i) for i in s.evidence_ids[:3]]
    removed = r.removed()
    out += ["", "## Removed or flagged bullets", ""]
    if not removed:
        out.append("None.")
    for name, b in removed:
        out.append(f"- {b.status.upper()} · {name}: \"{b.text}\" · {b.checker}: {b.reason}"
                   + (f" · cited {', '.join(f'E{i}' for i in b.evidence_ids)}" if b.evidence_ids else ""))
    path = Path(path)
    path.write_text("\n".join(out) + "\n")
    return path
